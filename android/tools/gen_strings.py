#!/usr/bin/env python3
"""Regenerate app/src/main/res/values*/strings_ios.xml from the iOS string catalog.

Usage (from android/): python3 -I tools/gen_strings.py
Android-only strings live in values*/strings.xml and are edited by hand.
"""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
CATALOG = ROOT.parent / "Bark" / "Localizable.xcstrings"
LOCALES = {"en": "values", "zh-Hans": "values-b+zh+Hans", "ja": "values-ja", "it": "values-it", "tr": "values-tr"}


JAVA_KEYWORDS = {"default", "import", "package", "class", "new", "return", "switch", "case", "public", "private", "static", "final", "this", "throw", "try", "catch", "do", "for", "if", "else", "while", "int", "long", "char", "byte", "short", "float", "double", "boolean", "void", "break", "continue", "goto", "const", "enum", "assert", "super", "native", "abstract", "interface", "extends", "implements", "instanceof", "synchronized", "transient", "volatile", "strictfp", "protected", "throws", "finally"}


def name(key):
    """Resource name for an iOS key; Java keywords (e.g. default, import) get a trailing underscore."""
    n = re.sub(r"[^A-Za-z0-9_]", "_", key)
    return n + "_" if n in JAVA_KEYWORDS else n


def escape(s):
    s = s.replace("\\", "\\\\").replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    s = s.replace("'", "\\'").replace('"', '\\"').replace("\n", "\\n")
    s = s.replace("%@", "%s")
    if s[:1] in ("@", "?"):
        s = "\\" + s
    return s


def main():
    strings = json.loads(CATALOG.read_text(encoding="utf-8"))["strings"]
    for locale, folder in LOCALES.items():
        lines = ['<?xml version="1.0" encoding="utf-8"?>', "<!-- Generated by tools/gen_strings.py, do not edit. -->",
                 # The iOS catalog has a few untranslated keys; Android falls back to English like iOS does.
                 '<resources xmlns:tools="http://schemas.android.com/tools" tools:ignore="MissingTranslation">']
        for key, entry in sorted(strings.items()):
            value = entry.get("localizations", {}).get(locale, {}).get("stringUnit", {}).get("value")
            if value is None:
                continue
            # '%' that is not a format specifier would break aapt's formatting check
            fmt = "" if re.search(r"%(\d+\$)?[sd@]", value) or "%" not in value else ' formatted="false"'
            lines.append(f'    <string name="{name(key)}"{fmt}>{escape(value)}</string>')
        lines.append("</resources>")
        out = ROOT / "app/src/main/res" / folder / "strings_ios.xml"
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text("\n".join(lines) + "\n", encoding="utf-8")
        print(out.relative_to(ROOT), len(lines) - 4)


if __name__ == "__main__":
    main()
